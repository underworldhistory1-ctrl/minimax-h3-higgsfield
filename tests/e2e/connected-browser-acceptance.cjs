const {chromium}=require(process.env.H3_TEST_PLAYWRIGHT || 'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const base=process.env.H3_PREVIEW_URL||'http://127.0.0.1:18772';
const output=process.env.H3_PREVIEW_SCREENSHOTS||path.resolve(__dirname,'../../.studio-preview/screenshots');
(async()=>{
  fs.mkdirSync(output,{recursive:true});
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.setDefaultTimeout(20000);const errors=[];page.on('pageerror',error=>errors.push(error.message));
  try{
    await page.goto(base+'/extensions/h3_studio/index.html');
    await page.waitForFunction(()=>state.promptProvider?.configured&&!state.projectLoading&&state.lorasLoaded);
    assert.match(await page.locator('#simulationBanner').textContent(),/No AI model has run/);
    assert.match(await page.locator('#writerStatus').textContent(),/SIMULATED/);
    const capturedStart=(await(await fetch(base+'/__captured')).json()).length;
    const reference=Buffer.from(await(await fetch(base+'/__fixtures/reference.png')).arrayBuffer());
    const video=Buffer.from(await(await fetch(base+'/__fixtures/motion.mp4')).arrayBuffer());
    const mask=Buffer.from(await(await fetch(base+'/__fixtures/mask.png')).arrayBuffer());
    await page.locator('[data-mode="refs"]').click();
    await page.locator('#refKind').selectOption('image');
    let chooserPromise=page.waitForEvent('filechooser');await page.locator('#addRef').click();
    await (await chooserPromise).setFiles({name:'hero.png',mimeType:'image/png',buffer:reference});
    await page.locator('#refKind').selectOption('video');
    chooserPromise=page.waitForEvent('filechooser');await page.locator('#addRef').click();
    await (await chooserPromise).setFiles({name:'camera.mp4',mimeType:'video/mp4',buffer:video});
    await page.locator('#refs .ref').nth(0).locator('.ref-fields select').selectOption('character identity');
    await page.locator('#refs .ref').nth(1).locator('.ref-fields select').selectOption('motion and camera');
    await page.locator('#prompt').fill('Use the attached character in a quiet station, following only the attached camera movement. No music or dialogue.');
    await page.locator('#preparationMode').selectOption('ai');
    let releasePreview,previewSeen,previewFinished;
    const previewGate=new Promise(resolve=>releasePreview=resolve);
    const previewRequest=new Promise(resolve=>previewSeen=resolve);
    const previewCompletion=new Promise(resolve=>previewFinished=resolve);
    await page.route('**/h3_studio/lab/prompt/prepare',async route=>{
      try{const response=await route.fetch();previewSeen();await previewGate;await route.fulfill({response});}catch{}finally{previewFinished();}
    });
    await page.locator('#preparePrompt').click();await previewRequest;
    await page.locator('#cancel').click();
    await page.waitForFunction(()=>!state.busy&&state.abortController===null);
    releasePreview();await previewCompletion;await page.unroute('**/h3_studio/lab/prompt/prepare');
    assert.equal(await page.evaluate(()=>state.preparedContext||null),null,'Cancelled preview cannot commit prepared output');
    await page.locator('#preparePrompt').click();
    await page.waitForFunction(()=>state.preparedContext&&!state.busy);
    assert.match(await page.locator('#compiledPromptDisplay').textContent(),/<Subject 1>/);
    assert.match(await page.locator('#compiledPromptDisplay').textContent(),/<Video 1>/);
    await page.locator('#prompt').fill('Use @hero in a quiet station with @camera camera guidance. No music or dialogue.');
    assert.equal(await page.locator('.prompt-highlight .reference-mention').count(),2);
    const overlay=await page.evaluate(()=>{const input=$('prompt');input.focus();input.setSelectionRange(4,4);const caret=input.selectionStart;input.setRangeText('the ',4,4,'end');return {text:input.value,caret:input.selectionStart,previous:caret,mirror:document.querySelector('.prompt-highlight').textContent};});
    assert.equal(overlay.caret,8);assert.equal(overlay.mirror.trim(),overlay.text);
    await page.locator('#loraList').evaluate(el=>el.closest('details').open=true);
    const motionLora=page.locator('#loraList .ref').filter({hasText:'Motion_Repair_V2'});
    await motionLora.locator('input[type="checkbox"]').check();
    await motionLora.locator('input[type="number"]').first().fill('0.65');await motionLora.locator('input[type="number"]').first().blur();
    await page.locator('#loraList').evaluate(el=>el.closest('details').open=false);
    await page.locator('#prompt').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(output,'H3_Studio_Desktop.png'),fullPage:true});
    await page.locator('#generate').click();
    await page.waitForFunction(()=>!state.busy&&!state.running&&state.current);
    const captures=await(await fetch(base+'/__captured')).json();assert.equal(captures.length,capturedStart+1);
    const graph=captures.at(-1).prompt;
    assert.ok(Object.values(graph).some(node=>node.class_type==='MiniMaxH3ReferenceToVideo'));
    assert.ok(Object.values(graph).some(node=>node.class_type==='LoraLoaderModelOnly'&&node.inputs.strength_model===0.65));
    assert.ok(!Object.values(graph).some(node=>node.class_type==='MiniMaxH3FunControlNetApply'));
    assert.ok(await page.locator('#stage').evaluate(el=>el.getBoundingClientRect().height)<390);
    await page.locator('#results .result-open').first().click();
    assert.equal(await page.locator('#settingsDialog').evaluate(el=>el.open),true,'Clicking a gallery card opens its details');
    assert.equal(await page.locator('#settingsContent .detail-prompt .reference-mention').count(),2);
    assert.ok(await page.locator('#settingsContent .detail-reference img').count()>=1);
    const detailText=await page.locator('#settingsContent').textContent();
    assert.match(detailText,/0.65/);assert.ok(!/Completed|Video length|Render time|Requested length/.test(detailText));
    await page.screenshot({path:path.join(output,'H3_Studio_Details.png'),fullPage:true});
    await page.locator('#settingsClose').click();
    await page.locator('[data-mode="text"]').click();
    await page.locator('#prompt').fill('A locked camera watches a still platform. No music or dialogue.');
    await page.locator('#durationSeconds').fill('5.2');await page.locator('#durationSeconds').blur();
    await page.locator('#controlPanel').evaluate(el=>el.open=true);
    await page.locator('#enableControl').check();await page.locator('#controlKind').selectOption('inpaint');
    await page.locator('#controlSource').setInputFiles({name:'source.mp4',mimeType:'video/mp4',buffer:video});
    await page.locator('#controlMask').setInputFiles({name:'mask.png',mimeType:'image/png',buffer:mask});
    await page.locator('#generate').click();
    for(let attempt=0;attempt<100;attempt++){
      if((await(await fetch(base+'/__captured')).json()).length===capturedStart+2)break;
      await page.waitForTimeout(100);
    }
    await page.waitForFunction(()=>!state.busy&&!state.running);
    const controlCapture=(await(await fetch(base+'/__captured')).json()).at(-1);
    assert.equal((await(await fetch(base+'/__captured')).json()).length,capturedStart+2);
    const controlNode=Object.values(controlCapture.prompt).find(node=>node.class_type==='MiniMaxH3FunControlNetApply');
    assert.ok(controlNode);assert.ok(controlNode.inputs.mask);assert.ok(controlNode.inputs.source_video);assert.ok(!controlNode.inputs.control_video);
    assert.ok(Object.values(controlCapture.prompt).some(node=>node.class_type==='MiniMaxH3ImageToVideo'));
    assert.ok(!Object.values(controlCapture.prompt).some(node=>node.class_type==='MiniMaxH3ReferenceToVideo'));
    await page.setViewportSize({width:390,height:844});
    await page.locator('#controlPanel').evaluate(el=>el.open=false);
    await page.locator('#loraList').evaluate(el=>el.closest('details').open=false);
    await page.evaluate(()=>window.scrollTo(0,0));
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
    await page.screenshot({path:path.join(output,'H3_Studio_Mobile.png'),fullPage:true});
    assert.deepEqual(errors,[]);
    console.log('PASS: local simulation, reference preparation, graph capture, LoRA settings, safe mentions, static-mask FL2VA, desktop/mobile screenshots. No GPU/provider inference.');
  }catch(error){console.error(await page.evaluate(()=>({error:document.querySelector('#error')?.textContent,preparation:document.querySelector('#preparationStatus')?.textContent,control:document.querySelector('#controlStatus')?.textContent,busy:state.busy})));throw error;}
  finally{await browser.close();}
})();
